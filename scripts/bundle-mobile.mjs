// Produce a self-contained HTML game as a Metro JS module: no hosted URL required.
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { build, createServer } from 'vite';

const root = fileURLToPath(new URL('../', import.meta.url));
const result = await build({
  root,
  configFile: false,
  logLevel: 'warn',
  build: {
    write: false,
    minify: true,
    cssCodeSplit: false,
    lib: { entry: resolve(root, 'src/main.ts'), name: 'FrameItGame', formats: ['iife'] },
  },
});
const outputs = (Array.isArray(result) ? result : [result]).flatMap(r => r.output);
const javascript = outputs.filter(item => item.type === 'chunk');
const styles = outputs.filter(item => item.type === 'asset' && item.fileName.endsWith('.css'));
if (javascript.length !== 1 || styles.length !== 1) throw new Error('Expected exactly one game script and stylesheet');
const script = javascript[0].code.replace(/<\/script/gi, '<\\/script');
const css = String(styles[0].source).replace(/<\/style/gi, '<\\/style');
const sourceHtml = await readFile(resolve(root, 'index.html'), 'utf8');
const html = sourceHtml
  .replace('<head>', () => '<head><script>window.addEventListener("error", function () { window.ReactNativeWebView?.postMessage(JSON.stringify({type:"game-error"})); });</script><style>' + css + '</style>')
  .replace(/<script type="module" src="\/src\/main.ts"><\/script>/, () => '<script>' + script + '</script>');
if (html.includes('src="/src/main.ts"')) throw new Error('Failed to replace the web entry point');
if (/<(?:script|link)\b[^>]*(?:src|href)=["'](?:https?:|\/assets\/)/i.test(html)) throw new Error('External runtime asset in mobile bundle');
const outputDir = resolve(root, 'mobile/generated');
// Use the same translations for native recovery screens and the in-game UI.
const server = await createServer({ root, configFile: false, server: { middlewareMode: true, hmr: false }, appType: 'custom' });
let nativeText;
try {
  const { ROWS } = await server.ssrLoadModule('/src/i18n/catalog.ts');
  const keys = ['Riprova', 'Impossibile avviare il gioco. Verifica che Android System WebView sia aggiornato e riprova.', 'Impossibile caricare il gioco. Tocca Riprova.', 'Il gioco è stato chiuso da Android. Tocca Riprova.'];
  const columns = { en: 1, it: 0, es: 2, fr: 3, de: 4 };
  nativeText = Object.fromEntries(Object.entries(columns).map(([language, column]) => [language, Object.fromEntries(keys.map(key => {
    const row = ROWS.find(row => row[0] === key);
    if (!row) throw new Error('Missing native translation: ' + key);
    return [key, row[column]];
  }))]));
} finally { await server.close(); }
await mkdir(outputDir, { recursive: true });
await writeFile(resolve(outputDir, 'game.js'), '// Generated by scripts/bundle-mobile.mjs; do not edit.\nexport const NATIVE_TEXT = ' + JSON.stringify(nativeText) + ';\nexport default ' + JSON.stringify(html) + ';\n');
console.log('Offline mobile game generated: ' + Buffer.byteLength(html) + ' bytes');
